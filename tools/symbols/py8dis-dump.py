"""Prints, as JSON, what py8dis makes of a binary under a control script: each piece of the binary where it
runs, every instruction and data line with its bytes, and the names the script gives.

    python3 -I tools/symbols/py8dis-dump.py <py8dis's package directory> <directory to run in> <control script>
        [its arguments]

The script runs in the directory given, where the paths it loads its binary from start, and its go() emits
nothing. Names py8dis makes up (l0070, sub_c1234), names acorn.py gives the OS and expressions (zp_ptr+1) are
left out.
"""

import json
import os
import runpy
import sys
import types

py8dis_dir, run_dir, script = (os.path.abspath(arg) for arg in sys.argv[1:4])
sys.path.insert(0, py8dis_dir)
sys.argv = [script] + sys.argv[4:]
os.chdir(run_dir)

import acorn  # noqa: E402
import classification  # noqa: E402
import commands  # noqa: E402
import disassembly  # noqa: E402
import labelmanager  # noqa: E402
import memorymanager  # noqa: E402
import movemanager  # noqa: E402

# Control scripts written for py8dis from September 2021 import these, since renamed or removed.
if "trace6502" not in sys.modules:
    trace6502 = types.ModuleType("trace6502")
    trace6502.hook_subroutine = commands.hook_subroutine
    sys.modules["trace6502"] = trace6502
if not hasattr(acorn, "add_standard_labels"):
    acorn.add_standard_labels = acorn.mos_labels

from_acorn = set()


def noting_acorn(command):
    def noted(runtime_addr, name=None, *args, **kwargs):
        if isinstance(name, str):
            from_acorn.add((int(runtime_addr), name))
        return command(runtime_addr, name, *args, **kwargs)

    return noted


# acorn.py looks these up in its own globals, which `from commands import *` filled.
for command in ["label", "optional_label", "subroutine", "entry", "hook_subroutine"]:
    if hasattr(acorn, command):
        setattr(acorn, command, noting_acorn(getattr(acorn, command)))


def dump():
    pieces = []
    for start, end in disassembly.calculate_move_ranges():
        move_id = movemanager.move_id_for_binary_addr[start]
        move = movemanager.move_definitions[move_id]
        statements = []
        pieces.append(
            {
                "binary": start,
                "runtime": int(move.convert_binary_to_runtime_addr(start)),
                "length": end - start,
                "move": int(move_id),
                "statements": statements,
            }
        )
        addr = start
        while addr < end:
            length = classification.get_classification(addr).length()
            statements.append(
                {
                    "at": int(move.convert_binary_to_runtime_addr(addr)),
                    "bytes": [memorymanager.memory_binary[a] for a in range(addr, addr + length)],
                    "code": bool(classification.is_code(addr)),
                }
            )
            addr += length
    labels = []
    for address, label in sorted(labelmanager.labels.items()):
        for move_id, names in sorted(label.explicit_names.items()):
            for name in names:
                if name.is_autogenerated or (int(address), name.text) in from_acorn:
                    continue
                labels.append({"name": name.text, "address": int(address), "move": int(move_id)})
    return {"pieces": pieces, "labels": labels}


go = commands.go
dump_output = sys.stdout


def go_quietly(*args, **kwargs):
    go(*args, **{**kwargs, "print_output": False})
    json.dump(dump(), dump_output)
    dump_output.flush()


commands.go = go_quietly
# Some scripts print a heading of their own before go().
sys.stdout = sys.stderr
runpy.run_path(script, run_name="__main__")
