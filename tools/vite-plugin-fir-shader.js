/**
 * Vite plugin to auto-generate FIR filter coefficients in GLSL shaders at build time.
 *
 * Looks for marked sections in .glsl files. The chroma section names its own parameters:
 *   // BEGIN_FIR_COEFFICIENTS
 *   // Cutoff: 2.217
 *   const int FIRTAPS = 51;
 *   float FIR[FIRTAPS];
 *   ... generated code ...
 *   // END_FIR_COEFFICIENTS
 *
 * The luma section is generated wholesale from luma-fir-generator.js:
 *   // BEGIN_LUMA_COEFFICIENTS
 *   const int LUMA_TAPS = 31;
 *   float LUMA_FIR[LUMA_TAPS];
 *   ... generated code ...
 *   // END_LUMA_COEFFICIENTS
 */

import { readFileSync } from "fs";
import { generateFirCoefficients } from "./fir-generator.js";
import { generateLumaCoefficients, LumaTaps } from "./luma-fir-generator.js";

const beginMarkerOf = (name) => `// BEGIN_${name}_COEFFICIENTS`;
const endMarkerOf = (name) => `// END_${name}_COEFFICIENTS`;

/**
 * Parse FIR parameters from the marker comment block.
 *
 * @param {string} markedSection - The text between BEGIN and END markers
 * @returns {{ cutoff: number, taps: number } | null} - Parsed parameters or null if invalid
 */
function parseFirParams(markedSection) {
    const cutoffMatch = markedSection.match(/\/\/\s*Cutoff:\s*(\d+(?:\.\d+)?)/);
    const tapsMatch = markedSection.match(/const\s+int\s+FIRTAPS\s*=\s*(\d+)/);

    if (!cutoffMatch || !tapsMatch) {
        return null;
    }

    return {
        cutoff: parseFloat(cutoffMatch[1]),
        taps: parseInt(tapsMatch[1], 10),
    };
}

/**
 * Generate the complete FIR coefficient section including markers. The
 * section replaces text that begins at the BEGIN marker, after the line's
 * indent, so the first line carries none of its own.
 *
 * @param {number} taps - Number of filter taps
 * @param {number} cutoff - Cutoff frequency in MHz
 * @param {string} indent - Indentation string to use (e.g., "    ")
 * @returns {string} - Complete marked section with generated code
 */
function generateFirSection(taps, cutoff, indent) {
    const coeffCode = generateFirCoefficients(taps, cutoff, indent);

    return `${beginMarkerOf("FIR")}
${indent}// Cutoff: ${cutoff}
${indent}const int FIRTAPS = ${taps};
${indent}float FIR[FIRTAPS];
${coeffCode}
${indent}${endMarkerOf("FIR")}`;
}

function generateLumaSection(indent) {
    return `${beginMarkerOf("LUMA")}
${indent}// Generated by tools/luma-fir-generator.js
${indent}const int LUMA_TAPS = ${LumaTaps};
${indent}float LUMA_FIR[LUMA_TAPS];
${generateLumaCoefficients(indent)}
${indent}${endMarkerOf("LUMA")}`;
}

/**
 * Replace the section of `code` between the `name` markers with what `generate`
 * makes of it, given the section's text and the indent of its BEGIN line.
 *
 * @returns {string | null} the transformed source, or null when the source has no such section
 * @throws {Error} when the markers are unpaired or out of order
 */
function replaceMarkedSection(code, name, generate) {
    const beginMarker = beginMarkerOf(name);
    const endMarker = endMarkerOf(name);
    const beginIdx = code.indexOf(beginMarker);
    const endIdx = code.indexOf(endMarker);
    if (beginIdx < 0 && endIdx < 0) {
        return null;
    }
    if (beginIdx < 0 || endIdx < 0) {
        throw new Error(`Unpaired ${name} marker`);
    }
    if (endIdx < beginIdx) {
        throw new Error(`Invalid ${name} marker order`);
    }

    const lineStart = code.lastIndexOf("\n", beginIdx) + 1;
    const indent = code.substring(lineStart, beginIdx);
    const section = code.substring(beginIdx, endIdx + endMarker.length);
    return code.replace(section, generate(section, indent));
}

/**
 * Replace the marked chroma section of a shader with freshly generated coefficients.
 *
 * @param {string} code - GLSL source
 * @returns {{ code: string, taps: number, cutoff: number } | null} the transformed
 *     source and the parameters it was generated from, or null when the source has
 *     no marked section
 * @throws {Error} when the marked section is malformed
 */
export function applyFirCoefficients(code) {
    let params;
    const replaced = replaceMarkedSection(code, "FIR", (section, indent) => {
        params = parseFirParams(section);
        if (!params) {
            throw new Error("Could not parse FIR parameters");
        }
        return generateFirSection(params.taps, params.cutoff, indent);
    });
    return replaced === null ? null : { code: replaced, ...params };
}

/**
 * Replace the marked luma section of a shader with the generator's kernel.
 *
 * @param {string} code - GLSL source
 * @returns {{ code: string, taps: number } | null} the transformed source and its
 *     tap count, or null when the source has no marked section
 * @throws {Error} when the marked section is malformed
 */
export function applyLumaCoefficients(code) {
    const replaced = replaceMarkedSection(code, "LUMA", (_, indent) => generateLumaSection(indent));
    return replaced === null ? null : { code: replaced, taps: LumaTaps };
}

/**
 * Vite plugin for FIR coefficient generation.
 */
export function firShaderPlugin() {
    return {
        name: "fir-shader-transform",
        enforce: "pre", // Run before Vite's internal transforms

        load(id) {
            // Only process .glsl files with ?raw suffix
            if (!id.includes(".glsl?raw")) {
                return null;
            }

            // Remove query parameters to get the actual file path
            const filePath = id.split("?")[0];
            const fileName = filePath.split("/").pop();

            // Read the file
            let code;
            try {
                code = readFileSync(filePath, "utf-8");
            } catch (err) {
                console.error(`[FIR Plugin] Failed to read ${filePath}:`, err);
                return null;
            }

            let chroma;
            let luma;
            try {
                chroma = applyFirCoefficients(code);
                luma = applyLumaCoefficients(chroma ? chroma.code : code);
            } catch (err) {
                console.warn(`[FIR Plugin] ${err instanceof Error ? err.message : err} in ${filePath}`);
                return null;
            }
            if (!chroma && !luma) {
                return null;
            }

            if (chroma) {
                console.log(`[FIR Plugin] Generated ${chroma.taps}-tap filter @ ${chroma.cutoff} MHz for ${fileName}`);
            }
            if (luma) {
                console.log(`[FIR Plugin] Generated ${luma.taps}-tap luma filter for ${fileName}`);
            }

            // Return as a JavaScript module exporting the string.
            // moduleType is required by Vite 8+ for non-.js file extensions.
            return {
                code: `export default ${JSON.stringify((luma ?? chroma).code)}`,
                map: null,
                moduleType: "js",
            };
        },
    };
}
